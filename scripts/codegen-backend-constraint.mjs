import { createRequire } from 'node:module'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(
  new URL('../apps/backend/package.json', import.meta.url),
)
const { Ajv2020 } = require('ajv/dist/2020.js')
const standaloneCode = require('ajv/dist/standalone/index.js')
const root = fileURLToPath(new URL('../', import.meta.url))
const schemaDirectory = resolve(root, 'apps/schema')
const output =
  process.argv[2] ??
  resolve(root, 'apps/backend/src/generated/constraint-validator.cjs')
const ajv = new Ajv2020({ code: { source: true }, strict: true })
for (const file of [
  'common',
  'min_gap_member',
  'min_gap_bands',
  'before',
  'at_position',
  'in_range',
  'count',
  'constraint',
]) {
  ajv.addSchema(
    JSON.parse(
      await readFile(resolve(schemaDirectory, `${file}.schema.json`), 'utf8'),
    ),
  )
}
const validate = ajv.getSchema(
  'https://setlist.local/schemas/constraint.schema.json',
)
await mkdir(resolve(output, '..'), { recursive: true })
await writeFile(
  output,
  '// Generated from apps/schema. DO NOT EDIT. Run npm run codegen.\n' +
    standaloneCode(ajv, validate) +
    '\n',
)
await writeFile(
  output.replace(/\.cjs$/, '.d.cts'),
  '// Generated by npm run codegen. DO NOT EDIT.\nimport type { Constraint } from "./constraint"\ndeclare function validate(value: unknown): value is Constraint\nexport = validate\n',
)
